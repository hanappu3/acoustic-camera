/**
 * Send a text string to the PC over the ST-LINK virtual COM port.
 * 文字列をST-LINKの仮想COMポート経由でPCへ送る。
 */
static void send_text(const char *s)
{
  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t *)s, strlen(s), 100);
}

/**
 * Wait for one result from a filter and read it. Returns 0 on success, -1 on timeout.
 * フィルタの結果を1個待って読む。成功で0、時間切れで-1を返す。
 */
static int read_one(DFSDM_Filter_HandleTypeDef *hf, int32_t *out)
{
  uint32_t ch;
  if (HAL_DFSDM_FilterPollForRegConversion(hf, 10) != HAL_OK) return -1;
  *out = HAL_DFSDM_FilterGetRegularValue(hf, &ch);
  return 0;
}

/**
 * Capture two mics at the same time and send "a,b" lines to the PC.
 * Conditions: Filter1 is "Synchronous with DFSDM0", so it starts together with Filter0.
 * Expected: START, 5000 lines of "a,b", END.
 * マイク2個を同時に取り込み、「a,b」の行でPCへ送る。
 * 条件：Filter1は「Filter0と同期」なので、Filter0と同時に動き出す。
 * 期待結果：START、「a,b」が5000行、END。
 */
static void capture_and_send(void)
{
  int32_t dummy;
  char line[40];

  /* 1. Arm Filter1 first (it waits for Filter0), then start Filter0.
        先にFilter1を待機させ、次にFilter0を開始 → 2つが同時に動き出す */
  HAL_DFSDM_FilterRegularStart(&hdfsdm1_filter1);
  HAL_DFSDM_FilterRegularStart(&hdfsdm1_filter0);

  /* 2. Discard the settling part / 落ち着くまでの部分を捨てる */
  for (int i = 0; i < N_SKIP; i++) {
    if (read_one(&hdfsdm1_filter0, &dummy) || read_one(&hdfsdm1_filter1, &dummy)) goto timeout;
  }

  /* 3. Read A and B alternately / AとBを交互に読む */
  for (int i = 0; i < N_SAMPLES; i++) {
    if (read_one(&hdfsdm1_filter0, &buf_a[i]) || read_one(&hdfsdm1_filter1, &buf_b[i])) goto timeout;
  }

  HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter0);
  HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter1);

  /* 4. Send to PC (about 7 s) / PCへ送る（約7秒） */
  send_text("START\r\n");
  for (int i = 0; i < N_SAMPLES; i++) {
    snprintf(line, sizeof(line), "%ld,%ld\r\n", (long)buf_a[i], (long)buf_b[i]);
    send_text(line);
  }
  send_text("END\r\n");
  return;

timeout:
  HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter0);
  HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter1);
  send_text("ERROR timeout\r\n");
}
