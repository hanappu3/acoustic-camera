/* Send a text string to the PC over the ST-LINK virtual COM port.
   ST-LINKの仮想COMポートで、文字列をPCへ送る */
static void send_text(const char *s)
{
  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t *)s, strlen(s), 100);
}

/* Capture N_SAMPLES from the PDM mic via DFSDM (polling), then send them as text.
   DFSDMでマイクの値をN_SAMPLES個取り込み（ポーリング）、文字でPCへ送る */
static void capture_and_send(void)
{
  uint32_t ch;
  char line[24];

  HAL_DFSDM_FilterRegularStart(&hdfsdm1_filter0);

  /* Discard the first outputs while the Sinc3 filter settles.
     Sinc3フィルタが落ち着くまでの最初の値は捨てる */
  for (int i = 0; i < 16; i++) {
    HAL_DFSDM_FilterPollForRegConversion(&hdfsdm1_filter0, 10);
    (void)HAL_DFSDM_FilterGetRegularValue(&hdfsdm1_filter0, &ch);
  }

  for (int i = 0; i < N_SAMPLES; i++) {
    if (HAL_DFSDM_FilterPollForRegConversion(&hdfsdm1_filter0, 10) != HAL_OK) {
      HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter0);
      send_text("ERROR timeout\r\n");   // no data from DFSDM / DFSDMから値が来ない
      return;
    }
    mic_buf[i] = HAL_DFSDM_FilterGetRegularValue(&hdfsdm1_filter0, &ch);
  }
  HAL_DFSDM_FilterRegularStop(&hdfsdm1_filter0);

  send_text("START\r\n");
  for (int i = 0; i < N_SAMPLES; i++) {
    snprintf(line, sizeof(line), "%ld\r\n", (long)mic_buf[i]);
    send_text(line);
  }
  send_text("END\r\n");
}

