/**
 * Send a text string to the PC over the ST-LINK virtual COM port.
 * 文字列をST-LINKの仮想COMポート経由でPCへ送る。
 */
static void send_text(const char *s)
{
  HAL_UART_Transmit(&hcom_uart[COM1], (uint8_t *)s, strlen(s), 100);
}

/** Stop all filters. / 全フィルタを止める。 */
static void stop_all(void)
{
  for (int c = 0; c < N_CH; c++) HAL_DFSDM_FilterRegularStop(filters[c]);
}

/**
 * Capture four mics at the same time and send "a,b,c,d" lines to the PC.
 * Conditions: Filters 1-3 are "Synchronous with DFSDM0", so all four start and
 *             finish each conversion together. We wait for Filter 0 only,
 *             then read all four values at once.
 * Expected: START, 2500 lines of "a,b,c,d", END.
 * マイク4個を同時に取り込み、「a,b,c,d」の行でPCへ送る。
 * 条件：Filter1〜3は「Filter0と同期」なので、4つは同時に変換を終える。
 *       Filter0の完了だけを待ち、4つの値をまとめて読む。
 * 期待結果：START、「a,b,c,d」が2500行、END。
 */
static void capture_and_send(void)
{
  uint32_t ch;
  char line[64];

  /* 1. Arm Filters 3,2,1 first (they wait), then start Filter 0.
        先にFilter3・2・1を待機させ、最後にFilter0を開始 → 4つが同時に動き出す */
  for (int c = N_CH - 1; c >= 0; c--) HAL_DFSDM_FilterRegularStart(filters[c]);

  /* 2. Capture. Samples before N_SKIP are read and thrown away.
        取り込み。N_SKIPより前のサンプルは読んで捨てる */
  for (int i = -N_SKIP; i < N_SAMPLES; i++) {
    if (HAL_DFSDM_FilterPollForRegConversion(filters[0], 10) != HAL_OK) {
      stop_all();
      send_text("ERROR timeout\r\n");
      return;
    }
    for (int c = 0; c < N_CH; c++) {
      int32_t v = HAL_DFSDM_FilterGetRegularValue(filters[c], &ch);
      if (i >= 0) buf[i][c] = v;
    }
  }
  stop_all();

  /* 3. Send to PC (about 7 s) / PCへ送る（約7秒） */
  send_text("START\r\n");
  for (int i = 0; i < N_SAMPLES; i++) {
    snprintf(line, sizeof(line), "%ld,%ld,%ld,%ld\r\n",
             (long)buf[i][0], (long)buf[i][1], (long)buf[i][2], (long)buf[i][3]);
    send_text(line);
  }
  send_text("END\r\n");
}
